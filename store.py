"""Local durable jobs and Windows-user-bound API secrets."""
import base64
import ctypes
import json
import os
import sqlite3
import threading
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DATA = Path(os.environ.get("VTS_DATA_DIR", str(ROOT / "data"))).resolve()
DATA.mkdir(parents=True, exist_ok=True)
(DATA / "jobs").mkdir(exist_ok=True)
LOCK = threading.RLock()


def connection():
    db = sqlite3.connect(DATA / "library.sqlite3", timeout=30)
    db.execute("PRAGMA journal_mode=WAL")
    return db


with connection() as db:
    db.execute("CREATE TABLE IF NOT EXISTS jobs (id TEXT PRIMARY KEY, body TEXT NOT NULL)")
    db.execute("CREATE TABLE IF NOT EXISTS settings (id INTEGER PRIMARY KEY, body TEXT NOT NULL)")


def jobs():
    with LOCK, connection() as db:
        return sorted([json.loads(r[0]) for r in db.execute("SELECT body FROM jobs")], key=lambda j: j["created"], reverse=True)


def job(job_id):
    with LOCK, connection() as db:
        row = db.execute("SELECT body FROM jobs WHERE id=?", (job_id,)).fetchone()
    if not row:
        raise KeyError(job_id)
    return json.loads(row[0])


def save_job(item):
    with LOCK, connection() as db:
        db.execute("INSERT OR REPLACE INTO jobs VALUES (?,?)", (item["id"], json.dumps(item, ensure_ascii=False)))


def update_job(job_id, **changes):
    with LOCK:
        item = job(job_id)
        # A cancelled/deleted job must never be resurrected by a late worker
        # callback. Explicit starts go through the control API below.
        control = changes.pop('_control', False)
        if item.get('delete_requested'):
            return item
        if item.get('title_override') and 'title' in changes and 'title_override' not in changes:
            changes.pop('title')
        if item['status'] == 'paused' and not control and changes.get('status') not in (None, 'queued', 'paused', 'deleting'):
            changes.pop('status')
            changes.pop('message', None)
        item.update(changes)
        item["updated"] = time.time()
        save_job(item)
        return item


def job_dir(job_id):
    # IDs are generated by the server; no user-provided filesystem paths.
    if len(job_id) != 32 or any(c not in "0123456789abcdef" for c in job_id):
        raise KeyError(job_id)
    folder = DATA / "jobs" / job_id
    folder.mkdir(exist_ok=True)
    return folder


def atomic_json(path, data):
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(json.dumps(data, ensure_ascii=False), encoding="utf-8")
    tmp.replace(path)


class Blob(ctypes.Structure):
    _fields_ = [("size", ctypes.c_ulong), ("data", ctypes.POINTER(ctypes.c_ubyte))]


def crypt(value: bytes, decrypt=False):
    if os.name != "nt":
        raise RuntimeError("此版本使用 Windows 本机账户加密 API Key。")
    buffer = ctypes.create_string_buffer(value)
    source = Blob(len(value), ctypes.cast(buffer, ctypes.POINTER(ctypes.c_ubyte)))
    result = Blob()
    fn = ctypes.windll.crypt32.CryptUnprotectData if decrypt else ctypes.windll.crypt32.CryptProtectData
    if not fn(ctypes.byref(source), None, None, None, None, 1, ctypes.byref(result)):
        raise RuntimeError("无法读取本机加密密钥，请重新输入 API Key。")
    try:
        return ctypes.string_at(result.data, result.size)
    finally:
        ctypes.windll.kernel32.LocalFree(result.data)


