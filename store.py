def settings(public=False):
    with LOCK, connection() as db:
        row = db.execute("SELECT body FROM settings WHERE id=1").fetchone()
    config = json.loads(row[0]) if row else json.loads(json.dumps(DEFAULT))
    config.setdefault("conversion_device", "auto")
    # Old installations gain new built-in services without resetting saved keys,
    # custom endpoints, model choices or the user's default service.
    existing = {p["id"] for p in config["providers"]}
    for preset in DEFAULT["providers"]:
        if preset["id"] not in existing:
            position = next((i for i, p in enumerate(config["providers"]) if p["id"] == "custom"), len(config["providers"]))
            config["providers"].insert(position, preset.copy())
    if public:
        for p in config["providers"]:
            p["has_key"] = bool(p.pop("key", ""))
    return config


def write_settings(config):
    with LOCK, connection() as db:
        db.execute("INSERT OR REPLACE INTO settings VALUES (1,?)", (json.dumps(config, ensure_ascii=False),))


def encode_key(value):
    return base64.b64encode(crypt(value.encode())).decode()


def provider(provider_id):
    item = next((p.copy() for p in settings()["providers"] if p["id"] == provider_id), None)
    if not item:
        raise ValueError("找不到所选 AI 服务，请重新选择。")
    item["api_key"] = crypt(base64.b64decode(item["key"]), True).decode() if item.get("key") else ""
    return item
